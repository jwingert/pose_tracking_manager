def labeling_recipe(alias, source_config, root=GEN_ROOT):
    """Python for a DLC shell: ground-truth labelling in the COMPANION project.

    The companion clones the alias's body parts so its labels are comparable, lives
    inside the set directory, and is never the training project -- ``merge_datasets``
    there would fold these labels into training and destroy the held-out property.
    """
    d = gen_dir(alias, root)
    existing = sorted(glob.glob(os.path.join(d, 'labels-%s-*' % alias)))
    videos = [e['link'] for e in list_videos(alias, root) if e['link'] and e['exists']]
    lines = ['import deeplabcut, yaml', '']
    if existing:
        cfg = os.path.join(existing[-1], 'config.yaml')
        lines += ['config = %r' % cfg,
                  '# add any set videos the companion is missing, then:',
                  'deeplabcut.add_new_videos(config, %r, copy_videos=False)' % videos]
    else:
        lines += ['bodyparts = yaml.safe_load(open(%r))["bodyparts"]' % str(source_config),
                  'config = deeplabcut.create_new_project(',
                  '    %r, "gen", %r,' % ('labels-%s' % alias, videos),
                  '    working_directory=%r, copy_videos=False)' % d,
                  'cfg = yaml.safe_load(open(config)); cfg["bodyparts"] = bodyparts',
                  'yaml.safe_dump(cfg, open(config, "w"))']
    lines += ['deeplabcut.extract_frames(config, userfeedback=False)',
              'deeplabcut.label_frames(config)      # needs an X display']
    return '\n'.join(lines)
