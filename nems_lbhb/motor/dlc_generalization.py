# interface to the generalization store that scripts/dlc_generalization_setup.py built for
# the Stage-1 evaluation -- held-out sessions were otherwise picked ad hoc per test, and
# nothing checked that a "held-out" session had not quietly entered training. This module
# follows THAT store's layout (videos/<Animal>_<stem>.avi + manifest.csv); it does not
# invent a second one. | date: 2026-08-18]
"""Per-alias generalization sets: the held-out videos a model is judged on.

Layout -- established by ``scripts/dlc_generalization_setup.py``, followed here::

    /auto/data/dlc/generalization/<alias>/
        videos/<Animal>_<session>.avi   symlink into /auto/data/daq (never a copy)
        manifest.csv                    the setup script's stratified selection
        manifest.json                   manual additions made from the GUI (this module)
        results.csv                     per-candidate spread from evaluation runs
        labels-<alias>-*/               optional companion DLC project for ground truth

Two manifests exist on purpose: ``manifest.csv`` is REGENERATED by the setup script, so
manual additions written into it would be clobbered on the next run.  The GUI's additions
live in ``manifest.json`` and :func:`list_videos` merges both with what is actually on
disk.

The one rule that makes the set mean anything: **a video in the set must never enter the
alias's training data.**  :func:`in_training` checks a session against a training
project's ``video_sets`` and ``labeled-data/``; adds are refused on a hit.

Ground-truth labelling happens in a COMPANION DLC project inside the set directory --
never in the training project, where ``merge_datasets`` would fold the labels into the
next training iteration and quietly destroy the held-out property.

Nothing here imports DeepLabCut or streamlit; the labelling recipe is emitted as text
for a DLC shell, matching how the curate step already works.
"""
import csv
import datetime
import glob
import json
import os

import yaml

GEN_ROOT = '/auto/data/dlc/generalization'


def gen_dir(alias, root=GEN_ROOT):
    return os.path.join(root, alias)


def videos_dir(alias, root=GEN_ROOT):
    return os.path.join(gen_dir(alias, root), 'videos')


def _manifest_json(alias, root=GEN_ROOT):
    return os.path.join(gen_dir(alias, root), 'manifest.json')


def _manifest_csv(alias, root=GEN_ROOT):
    return os.path.join(gen_dir(alias, root), 'manifest.csv')


def session_stem(video_path):
    """The session a video belongs to, however the path was given."""
    base = os.path.basename(str(video_path))
    if base.startswith(('recording', 'video_')):
        return os.path.basename(os.path.dirname(str(video_path)))
    return os.path.splitext(base)[0]


def _split_link_name(name):
    """``'Prince_PRN024a01_a_NTD'`` -> ``('Prince', 'PRN024a01_a_NTD')``.

    The animal prefix is the setup script's convention; animal names carry no
    underscore, so the first one is the separator.
    """
    stem = os.path.splitext(name)[0]
    if '_' in stem:
        animal, session = stem.split('_', 1)
        return animal, session
    return None, stem


def _animal_of(video_path):
    """Animal from a daq path (``/auto/data/daq/<Animal>/...``), or None."""
    parts = os.path.normpath(str(video_path)).split(os.sep)
    if 'daq' in parts:
        i = parts.index('daq')
        if i + 1 < len(parts):
            return parts[i + 1]
    return None


def _load_json(alias, root=GEN_ROOT):
    path = _manifest_json(alias, root)
    if not os.path.exists(path):
        return []
    try:
        with open(path, 'r') as f:
            return json.load(f)
    except Exception:                                          # noqa: BLE001
        return []


def _load_csv(alias, root=GEN_ROOT):
    path = _manifest_csv(alias, root)
    if not os.path.exists(path):
        return []
    try:
        with open(path, 'r', newline='') as f:
            return list(csv.DictReader(f))
    except Exception:                                          # noqa: BLE001
        return []


def list_videos(alias, root=GEN_ROOT):
    """The set's entries: ``videos/`` on disk joined to both manifests.

    A manifest row whose symlink or target has gone missing is still listed, flagged
    ``exists=False`` -- evidence that quietly disappeared should read as damage, not as
    a smaller set.
    """
    by_session = {}
    for row in _load_csv(alias, root):                        # setup script's selection
        by_session[row.get('video_stem')] = {
            'added_by': 'dlc_generalization_setup',
            'note': row.get('eval_mode'), 'animal': row.get('animal'),
            'added': None, 'target': row.get('avi_path')}
    for row in _load_json(alias, root):                       # manual GUI additions
        by_session[row.get('session')] = {
            'added_by': row.get('added_by'), 'note': row.get('note'),
            'animal': row.get('animal'), 'added': row.get('added'),
            'target': row.get('target')}

    entries, seen = [], set()
    for link in sorted(glob.glob(os.path.join(videos_dir(alias, root), '*.avi'))):
        animal, session = _split_link_name(os.path.basename(link))
        meta = by_session.get(session, {})
        entries.append({
            'session': session, 'animal': meta.get('animal') or animal,
            'link': link, 'target': os.path.realpath(link),
            'exists': os.path.exists(os.path.realpath(link)),
            'added_by': meta.get('added_by'), 'added': meta.get('added'),
            'note': meta.get('note'),
        })
        seen.add(session)
    for session, meta in by_session.items():
        if session in seen or session is None:
            continue
        entries.append({'session': session, 'animal': meta.get('animal'),
                        'link': None, 'target': meta.get('target'), 'exists': False,
                        'added_by': meta.get('added_by'), 'added': meta.get('added'),
                        'note': meta.get('note')})
    return entries


def training_sessions(project_config):
    """Session stems the training project already knows about.

    Both sources matter: ``video_sets`` is what ``merge_datasets`` trains from, and a
    ``labeled-data/`` folder outside ``video_sets`` is one ``add_new_videos`` call away
    from entering it.
    """
    sessions = set()
    try:
        with open(project_config, 'r') as f:
            cfg = yaml.safe_load(f)
        for v in (cfg.get('video_sets') or {}):
            sessions.add(os.path.splitext(os.path.basename(str(v)))[0])
    except Exception:                                          # noqa: BLE001
        pass
    labeled = os.path.join(os.path.dirname(str(project_config)), 'labeled-data')
    if os.path.isdir(labeled):
        for name in os.listdir(labeled):
            if os.path.isdir(os.path.join(labeled, name)):
                sessions.add(name)
    return sessions


def in_training(session, project_config):
    """True when the training project already contains this session's frames.

    Substring match, not equality: ``add_video_to_dataset`` renames a copied video to
    ``<session>_<basename>.avi``, so the training name contains the session stem rather
    than equalling it.
    """
    if not project_config:
        return False
    return any(session in t for t in training_sessions(project_config))


def add_video(alias, video_path, by, note='', project_config=None, root=GEN_ROOT):
    """Symlink a video into ``<alias>/videos/`` and record who added it.

    Refuses a missing file, a duplicate session, and -- when ``project_config`` is given
    -- a session already in that training project: an entry that overlaps training is
    not generalization evidence, and adding it anyway would let every later claim lean
    on a contaminated set.

    The record goes to ``manifest.json``, never ``manifest.csv``: the CSV belongs to the
    setup script and is regenerated wholesale, so a manual row written there would be
    clobbered on its next run.
    """
    video_path = os.path.abspath(str(video_path))
    if not os.path.exists(video_path):
        raise FileNotFoundError('no video at %s' % video_path)
    session = session_stem(video_path)
    if project_config and in_training(session, project_config):
        raise ValueError('%s is in the training project already -- it cannot be '
                         'generalization evidence' % session)
    if any(e['session'] == session for e in list_videos(alias, root)):
        raise ValueError('%s is already in the %s generalization set'
                         % (session, alias))

    d = videos_dir(alias, root)
    os.makedirs(d, exist_ok=True)
    animal = _animal_of(video_path) or 'unknown'
    link = os.path.join(d, '%s_%s.avi' % (animal, session))
    os.symlink(video_path, link)

    manifest = _load_json(alias, root)
    manifest.append({
        'session': session, 'animal': animal, 'target': video_path, 'added_by': str(by),
        'added': datetime.datetime.now(datetime.timezone.utc).isoformat(),
        'note': str(note or ''),
    })
    tmp = _manifest_json(alias, root) + '.tmp'
    with open(tmp, 'w') as f:
        json.dump(manifest, f, indent=2)
    os.replace(tmp, _manifest_json(alias, root))
    return link


def results_summary(alias, root=GEN_ROOT):
    """``{'rows': N, 'candidates': [...]}`` from the set's ``results.csv``, or None.

    The Stage-1 evaluation wrote per-(candidate, video) spread there; surfacing that it
    exists keeps the GUI from claiming a set has never been evaluated when it has.
    """
    path = os.path.join(gen_dir(alias, root), 'results.csv')
    if not os.path.exists(path):
        return None
    try:
        with open(path, 'r', newline='') as f:
            rows = list(csv.DictReader(f))
    except Exception:                                          # noqa: BLE001
        return None
    if not rows:
        return None
    return {'rows': len(rows), 'path': path,
            'candidates': sorted({r.get('candidate') for r in rows if r.get('candidate')})}


