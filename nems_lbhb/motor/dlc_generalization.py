# inference over WHOLE generalization videos (50k-170k frames, ~35-60 GPU-min each), which
# priced the loop out of routine use. Spread is a per-frame statistic, so ~750 uniformly
# sampled frames measure the same thing at ~1/40th the compute -- an unsupervised
# generalization number cheap enough to run on every candidate. | date: 2026-08-18]
DEFAULT_SAMPLE_FRAMES = 750


def sample_video(video_path, out_path, n_frames=DEFAULT_SAMPLE_FRAMES):
    """Write ``out_path``: ``n_frames`` uniformly sampled from ``video_path``.

    Uniform over the WHOLE video, never a contiguous block -- 750 consecutive frames is
    25 seconds of one behaviour, and a spread measured there describes a posture, not a
    session.  A sidecar ``<out>.frames.json`` records the source and the exact indices,
    so a number computed on the sample stays attributable.
    """
    import cv2
    cv2.setLogLevel(0)
    cap = cv2.VideoCapture(str(video_path))
    total = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    if total <= 0:
        cap.release()
        raise ValueError('unreadable video: %s' % video_path)
    n = min(int(n_frames), total)
    idx = [int(round(i * (total - 1) / max(n - 1, 1))) for i in range(n)]

    fps = cap.get(cv2.CAP_PROP_FPS) or 30.0
    w = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    h = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    os.makedirs(os.path.dirname(str(out_path)), exist_ok=True)
    writer = cv2.VideoWriter(str(out_path), cv2.VideoWriter_fourcc(*'MJPG'),
                             fps, (w, h))
    written = []
    try:
        for i in idx:
            cap.set(cv2.CAP_PROP_POS_FRAMES, i)
            ok, frame = cap.read()
            if not ok:
                continue
            writer.write(frame)
            written.append(i)
    finally:
        cap.release()
        writer.release()
    if not written:
        raise ValueError('no frames could be read from %s' % video_path)
    with open(str(out_path) + '.frames.json', 'w') as f:
        json.dump({'source': str(video_path), 'n_total': total,
                   'frame_indices': written}, f)
    return str(out_path)


def resolved_snapshot(candidate_config):
    """The snapshot number the config's ``snapshotindex`` selects, or None.

    Recorded with every result row: 'merged_left_chimney' names a PROJECT, and a project
    serves different networks as its config moves -- two evaluations at different
    snapshots landed in results_sampled.csv indistinguishable, which is the same
    identity hole gDLCFit exists to close for production fits.
    """
    try:
        with open(str(candidate_config), 'r') as f:
            cfg = yaml.safe_load(f)
        project = os.path.dirname(os.path.abspath(str(candidate_config)))
        pattern = os.path.join(project, 'dlc-models',
                               'iteration-%d' % int(cfg.get('iteration', 0)),
                               '*', 'train', 'snapshot-*.index')
        snaps = sorted({int(os.path.basename(p).split('-')[1].split('.')[0])
                        for p in glob.glob(pattern)})
        if not snaps:
            return None
        return snaps[int(cfg.get('snapshotindex', -1))]
    except Exception:                                          # noqa: BLE001
        return None


def _append_rows(path, rows):
    """Append result rows, rewriting the file when the schema has grown.

    ``csv.DictWriter`` against an old header silently misaligns any NEW field into the
    wrong column; when the union of fieldnames differs from the existing header the
    whole file is rewritten with the union (old rows get '' for fields they predate).
    """
    old = []
    if os.path.exists(path):
        with open(path, 'r', newline='') as f:
            old = list(csv.DictReader(f))
    fields = list(dict.fromkeys(
        [k for r in old for k in r] + [k for r in rows for k in r]))
    # write-then-replace: results come from BOTH the queue (as lbhb) and user shells, and
    # a 0644 file owned by the other account cannot be opened 'w' -- but the 0777
    # directory allows a rename over it. 0666 keeps the next writer, whoever it is, able
    # to do the same.
    tmp = path + '.tmp'
    with open(tmp, 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=fields, restval='')
        w.writeheader()
        w.writerows(old + rows)
    os.chmod(tmp, 0o666)
    os.replace(tmp, path)


def _h5_for_snapshot(out_dir, stem, snap):
    """The prediction file for THIS snapshot -- an error when it cannot be identified.

    ``sorted(...)[-1]`` scored whichever output sorted last: a snapshot-150000
    evaluation silently re-scored the 160000 run's predictions, because
    ``_160000.h5`` sorts after ``_150000.h5``.  Attribution by anything other than
    the resolved identity is the failure mode this whole lifecycle exists to kill,
    so no match raises rather than guessing.
    """
    h5s = sorted(glob.glob(os.path.join(out_dir, stem + 'DLC*.h5')))
    if snap is not None:
        h5s = [p for p in h5s if p.endswith('_%d.h5' % int(snap))]
    elif len(h5s) > 1:
        raise RuntimeError(
            'cannot attribute predictions for %s: %d DLC outputs in %s and the '
            'candidate snapshot is unresolvable' % (stem, len(h5s), out_dir))
    if not h5s:
        raise RuntimeError('no DLC output for %s at snapshot %s in %s'
                           % (stem, snap, out_dir))
    return h5s[-1]


def evaluate_candidate(alias, candidate_config, n_frames=DEFAULT_SAMPLE_FRAMES,
                       p_cut=0.2, root=GEN_ROOT):
    """Sampled inference + Procrustes spread for one candidate over the alias's set.

    Per video: sample ``n_frames`` uniformly, run the candidate over the sample, head-fix
    and Procrustes-align the predictions, and score spread -- against the candidate's own
    training labels when it has them (``ratio_spread``), unsupervised otherwise
    (``rms_spread`` in head-lengths, comparable across candidates on the same video).

    Appends one row per video to ``<alias>/results_sampled.csv`` -- its OWN file, not the
    Stage-1 ``results.csv``, whose schema belongs to the setup script.  Runs DLC, so it
    needs a GPU shell (hyena); the GUI emits it as a recipe like the other heavy steps.
    """
    import deeplabcut                                          # lazy: GPU env only
    from nems_lbhb.motor import dlc_headfix_qc as hfqc
    from nems_lbhb.motor.dlc_fit_qc import QC_MODULE_VERSION as qc_version

    candidate = os.path.basename(os.path.dirname(os.path.abspath(str(candidate_config))))
    out_dir = os.path.join(gen_dir(alias, root), 'inference',
                           '%s_sampled%d' % (candidate, int(n_frames)))
    # evaluations run from BOTH the queue (as lbhb) and user shells, so anything this
    # function creates must stay writable to the other account -- the first queued run
    # died on exactly this, mkdir refused inside a user-owned inference/
    os.makedirs(os.path.join(out_dir, 'samples'), exist_ok=True)
    for d in (os.path.dirname(out_dir), out_dir, os.path.join(out_dir, 'samples')):
        try:
            os.chmod(d, 0o777)
        except OSError:
            pass                                               # someone else's dir: fine
    reference = None
    try:
        reference = hfqc.build_training_reference(candidate_config)
    except Exception:                                          # noqa: BLE001
        pass

    rows = []
    for entry in list_videos(alias, root):
        if not (entry['link'] and entry['exists']):
            continue
        sampled = os.path.join(out_dir, 'samples',
                               os.path.basename(entry['link']))
        if not os.path.exists(sampled):
            sample_video(entry['link'], sampled, n_frames=n_frames)
        deeplabcut.analyze_videos(str(candidate_config), [sampled],
                                  videotype='avi', destfolder=out_dir)
        stem = os.path.splitext(os.path.basename(sampled))[0]
        h5 = _h5_for_snapshot(out_dir, stem, resolved_snapshot(candidate_config))
        result = hfqc.score_video(h5, reference, p_cut=p_cut)
        doc = hfqc.summarize(result)
        rows.append({
            'alias': alias, 'candidate': candidate,
            'snapshot': resolved_snapshot(candidate_config),
            'session': entry['session'],
            'animal': entry.get('animal'), 'n_sampled': int(result.n_total),
            'p_cut': p_cut,
            # summarize's headline: mean over rigid markers EXCLUDING the head-fix
            # origin, whose spread is zero by construction under QC v5
            'rms_spread_mean': round(float(doc['rms_spread_mean']), 5)
                               if doc['rms_spread_mean'] is not None else None,
            # QC v6 companion: self-Procrustes spread, all rigid markers share the fit
            'rms_spread_proc_mean': round(float(doc['rms_spread_proc_mean']), 5)
                                    if doc.get('rms_spread_proc_mean') is not None
                                    else None,
            'ratio_mean': doc['ratio_mean'], 'ratio_worst': doc['ratio_worst'],
            'track_mean': doc['track_mean'], 'frac_valid': doc['frac_valid'],
            'scale_px': doc['scale_px'],
            'has_reference': doc['has_reference'],
            # rows from different QC versions are not comparable -- filter the matrix
            'qc_version': qc_version,
            'computed_utc': datetime.datetime.now(datetime.timezone.utc).isoformat(),
        })

    if rows:
        _append_rows(os.path.join(gen_dir(alias, root), 'results_sampled.csv'), rows)
    return rows


